
from pathlib import Path

from langchain_community.vectorstores import FAISS
from langchain_text_splitters import RecursiveCharacterTextSplitter

from config import (
    RAG_INDEX_DIR,
    CHUNK_SIZE,
    CHUNK_OVERLAP,
)

from modules.rag.document_loader import load_knowledge_documents
from modules.rag.embeddings import get_embedding_model


# ==========================================
# 1. VECTOR STORE CONFIGURATION
# ==========================================

INDEX_PATH = Path(RAG_INDEX_DIR)

INDEX_FILE = INDEX_PATH / "index.faiss"
METADATA_FILE = INDEX_PATH / "index.pkl"


# ==========================================
# 2. SPLIT DOCUMENTS INTO CHUNKS
# ==========================================

def split_documents(documents):
    """
    Split agricultural documents into smaller chunks.
    Original metadata is preserved in every chunk.
    """

    if not documents:
        raise ValueError("No documents provided for chunking.")

    splitter = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE,
        chunk_overlap=CHUNK_OVERLAP,
        separators=[
            "\n\n",
            "\n",
            ". ",
            " ",
            ""
        ]
    )

    chunks = splitter.split_documents(documents)

    if not chunks:
        raise ValueError("Document chunking produced no results.")

    return chunks


# ==========================================
# 3. BUILD FAISS VECTOR DATABASE
# ==========================================

def build_vector_store(force_rebuild=False):
    """
    Load knowledge documents, split them, generate embeddings
    and save the FAISS index locally.

    force_rebuild=True rebuilds the existing index.
    """

    INDEX_PATH.mkdir(
        parents=True,
        exist_ok=True
    )

    if not force_rebuild and INDEX_FILE.exists() and METADATA_FILE.exists():
        return {
            "status": "already_exists",
            "message": "Existing FAISS index found.",
            "index_path": str(INDEX_PATH)
        }

    # Load agricultural documents
    result = load_knowledge_documents()

    documents = result["documents"]

    # Split documents
    chunks = split_documents(documents)

    # Load embedding model
    embedding_model = get_embedding_model()

    # Create FAISS index
    vector_store = FAISS.from_documents(
        documents=chunks,
        embedding=embedding_model
    )

    # Save index and metadata
    vector_store.save_local(
        str(INDEX_PATH)
    )

    return {
        "status": "created",
        "total_files": result["total_files"],
        "total_pages_or_sections": result["total_pages_or_sections"],
        "total_chunks": len(chunks),
        "failed_files": result["failed_files"],
        "index_path": str(INDEX_PATH)
    }


# ==========================================
# 4. LOAD EXISTING VECTOR DATABASE
# ==========================================

def load_vector_store():
    """
    Load an existing FAISS index without rebuilding it.

    Only load indexes generated by this trusted application.
    """

    if not INDEX_FILE.exists() or not METADATA_FILE.exists():
        raise FileNotFoundError(
            "FAISS index not found. Build the knowledge base first."
        )

    embedding_model = get_embedding_model()

    vector_store = FAISS.load_local(
        str(INDEX_PATH),
        embedding_model,
        allow_dangerous_deserialization=True
    )

    return vector_store


# ==========================================
# 5. SEARCH RELEVANT DOCUMENTS
# ==========================================

def search_documents(question, k=4):
    """
    Retrieve the most relevant document chunks
    for a farmer's question.
    """

    if not question or not question.strip():
        raise ValueError("Question cannot be empty.")

    vector_store = load_vector_store()

    results = vector_store.similarity_search(
        question.strip(),
        k=k
    )

    return results


# ==========================================
# 6. VECTOR STORE INFORMATION
# ==========================================

def get_vector_store_info():

    if not INDEX_FILE.exists() or not METADATA_FILE.exists():
        return {
            "exists": False,
            "index_path": str(INDEX_PATH)
        }

    vector_store = load_vector_store()

    return {
        "exists": True,
        "total_vectors": vector_store.index.ntotal,
        "index_path": str(INDEX_PATH)
    }
